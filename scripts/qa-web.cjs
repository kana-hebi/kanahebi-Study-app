    await page.screenshot({ path: 'artifacts/polymer-diagram-zoom-mobile.png', fullPage: true });
    await page.getByRole('button', { name: '図を閉じる', exact: true }).click();
    assert.equal(await page.evaluate(() => localStorage.getItem('kanahebi-study.v1')), lessonBefore);
    tests.push('rich lesson renders diagram, hides then opens worked solution and zooms without learner writes');
    const next = organic.nodes.find(n => n.id === foundation.lesson.relatedNodeIds[0]);
    await page.getByRole('button', { name: next.title, exact: true }).last().click();
    assert.ok(await page.getByText(next.lesson.core, { exact: true }).isVisible());
    tests.push('related lesson navigation connects polymer instruction');
