    await page.getByRole('button', { name: '全教材', exact: true }).click();
    tests.push('home polymer exercise route includes all 40 deep topics across synthetic and natural units');
    await page.getByRole('switch', { name: '学習記録' }).uncheck();
    await page.getByRole('textbox', { name: '知識を検索', exact: true }).fill('置換側');
    await page.getByRole('button', { name: 'この知識で絞る', exact: true }).click();
